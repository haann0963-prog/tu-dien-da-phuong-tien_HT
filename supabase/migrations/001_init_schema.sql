-- 2. BẬT ROW LEVEL SECURITY (RLS) & PHÂN QUYỀN
-- ==========================================

ALTER TABLE public.words ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.videos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.community_posts ENABLE ROW LEVEL SECURITY;

-- Policy cho bảng WORDS
CREATE POLICY "Public can view approved words"
    ON public.words FOR SELECT
    USING (status = 'approved');

CREATE POLICY "Public can submit pending words"
    ON public.words FOR INSERT
    WITH CHECK (status = 'pending');

CREATE POLICY "Admin full access on words"
    ON public.words FOR ALL
    TO authenticated
    USING (true)
    WITH CHECK (true);

