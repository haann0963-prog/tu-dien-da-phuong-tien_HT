-- ==========================================
-- 1. TẠO CÁC BẢNG DỮ LIỆU CHÍNH
-- ==========================================

-- Bảng Từ vựng phương ngữ
CREATE TABLE IF NOT EXISTS public.words (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word TEXT NOT NULL,
    meaning TEXT NOT NULL,
    context TEXT,
    poetry TEXT,
    image_url TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Bảng Video giao tiếp & Dân ca Ví, Giặm
CREATE TABLE IF NOT EXISTS public.videos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL CHECK (category IN ('communication', 'folksong')),
    youtube_url TEXT NOT NULL,
    description TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Bảng Bài viết cộng đồng & Di sản văn hóa
CREATE TABLE IF NOT EXISTS public.community_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    author TEXT NOT NULL,
    image_url TEXT,
    content TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Index tối ưu truy vấn lọc theo trạng thái và tìm kiếm
CREATE INDEX IF NOT EXISTS idx_words_status_created ON public.words (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_words_word ON public.words (word);
CREATE INDEX IF NOT EXISTS idx_videos_status_created ON public.videos (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_posts_status_created ON public.community_posts (status, created_at DESC);

-- Trigger tự động cập nhật updated_at khi sửa từ vựng
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$ BEGIN NEW.updated_at = now(); RETURN NEW; END; $$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_words_updated_at ON public.words;
CREATE TRIGGER trg_words_updated_at
    BEFORE UPDATE ON public.words
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_updated_at();

